"""Generate the fire-adb app icon for every supported platform.

The single source of truth is the app_icon.svg at the repository root
(rounded-square background + centered flame). This script renders it and
auto-detects which platform folders exist under the Flutter project root
(android/ios/linux/macos/web/windows), generating icons only for the
platforms that are present.
"""
import io
import json
import os

import cairosvg
from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.join(REPO, "app")
SOURCE_SVG = os.path.join(REPO, "app_icon.svg")
CANVAS = 1024


def render_master() -> Image.Image:
    if not os.path.isfile(SOURCE_SVG):
        raise SystemExit(f"source icon not found: {SOURCE_SVG}")
    master_png = os.path.join(ROOT, "assets", "icon", "flame_master.png")
    os.makedirs(os.path.dirname(master_png), exist_ok=True)
    cairosvg.svg2png(url=SOURCE_SVG, write_to=master_png,
                     output_width=CANVAS, output_height=CANVAS)
    return Image.open(master_png).convert("RGBA")


def save_scaled(master: Image.Image, path: str, size: int) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    master.resize((size, size), Image.LANCZOS).save(path)
    print(f"  {size:>4}px -> {os.path.relpath(path, ROOT)}")


def has_platform(name: str) -> bool:
    return os.path.isdir(os.path.join(ROOT, name))


def gen_android(master: Image.Image) -> None:
    densities = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for dpi, size in densities.items():
        save_scaled(master, os.path.join(
            ROOT, "android", "app", "src", "main", "res",
            f"mipmap-{dpi}", "ic_launcher.png"), size)


def gen_appiconset(master: Image.Image, path: str) -> None:
    """Generate an Apple .appiconset from its Contents.json manifest."""
    manifest = os.path.join(path, "Contents.json")
    with open(manifest, encoding="utf-8") as f:
        images = json.load(f)["images"]
    for entry in images:
        filename = entry.get("filename")
        if not filename:
            continue  # single-size placeholder entries
        size, scale = entry["size"], entry.get("scale", "1x")
        width = int(float(size.split("x")[0]) * float(scale.rstrip("x")))
        save_scaled(master, os.path.join(path, filename), width)


def gen_windows(master: Image.Image) -> None:
    ico = os.path.join(ROOT, "windows", "runner", "resources", "app_icon.ico")
    os.makedirs(os.path.dirname(ico), exist_ok=True)
    master.save(ico, format="ICO",
                sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64),
                       (128, 128), (256, 256)])
    print(f"   ICO -> {os.path.relpath(ico, ROOT)}")


def gen_linux(master: Image.Image) -> None:
    """Embed a 512px PNG as a C byte array for the Linux GTK runner."""
    buf = io.BytesIO()
    master.resize((512, 512), Image.LANCZOS).save(buf, "PNG", optimize=True)
    data = buf.getvalue()

    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    body = "\n".join(lines).rstrip(",")

    header = os.path.join(ROOT, "linux", "runner", "app_icon.h")
    os.makedirs(os.path.dirname(header), exist_ok=True)
    with open(header, "w", encoding="utf-8") as f:
        f.write(
            "// Generated by scripts/gen_app_icon.py. Do not edit.\n"
            "#ifndef APP_ICON_H_\n"
            "#define APP_ICON_H_\n\n"
            "static const unsigned char kAppIconPng[] = {\n"
            + body + "\n"
            "};\n\n"
            f"static const unsigned int kAppIconPngSize = {len(data)};\n\n"
            "#endif  // APP_ICON_H_\n"
        )
    print(f"  512px -> {os.path.relpath(header, ROOT)} ({len(data)} bytes)")


def gen_web(master: Image.Image) -> None:
    save_scaled(master, os.path.join(ROOT, "web", "favicon.png"), 16)
    save_scaled(master, os.path.join(ROOT, "web", "icons", "Icon-192.png"), 192)
    save_scaled(master, os.path.join(ROOT, "web", "icons", "Icon-512.png"), 512)
    save_scaled(master, os.path.join(ROOT, "web", "icons", "Icon-maskable-192.png"), 192)
    save_scaled(master, os.path.join(ROOT, "web", "icons", "Icon-maskable-512.png"), 512)


def main() -> None:
    master = render_master()

    generators = {
        "android": gen_android,
        "ios": lambda m: gen_appiconset(
            m, os.path.join(ROOT, "ios", "Runner", "Assets.xcassets", "AppIcon.appiconset")),
        "linux": gen_linux,
        "macos": lambda m: gen_appiconset(
            m, os.path.join(ROOT, "macos", "Runner", "Assets.xcassets", "AppIcon.appiconset")),
        "web": gen_web,
        "windows": gen_windows,
    }
    for name, gen in generators.items():
        if has_platform(name):
            print(f"[{name}]")
            gen(master)
        else:
            print(f"[{name}] skipped (no {name}/ directory)")
    print("Done.")


if __name__ == "__main__":
    main()
